class Translator:
    def __init__(self, lang="th"):
        self.lang = lang if lang in LANGS else "th"
        self.extra = {}                 # texts added by the modules (their plugin's texts()): {lang: {key: text}}

    def add_texts(self, texts):
        """Add the texts of a module: {"th": {key: text}, "en": {...}}. A key of the shell is never replaced."""
        for lang, table in (texts or {}).items():
            self.extra.setdefault(lang, {}).update({k: v for k, v in table.items() if k not in TEXT.get(lang, {})})

    def set_lang(self, lang):
        if lang in LANGS:
            self.lang = lang

    def t(self, key, **kwargs):
        text = TEXT.get(self.lang, {}).get(key)
        if text is None:
            text = self.extra.get(self.lang, {}).get(key)
        if text is None:
            text = TEXT["en"].get(key, self.extra.get("en", {}).get(key, key))
        try:
            return text.format(**kwargs) if kwargs else text
        except (KeyError, IndexError):
            return text
